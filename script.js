    function copyClone(url, event) {
      if (event) event.stopPropagation();
      const cmd = `git clone ${url}`;
      navigator.clipboard.writeText(cmd).then(() => {
        showToast(`Copied: ${cmd}`);
      }).catch(() => {
        showToast('Copied clone command');
      });
    }

