    function exportSubscribers() {
      let subs = JSON.parse(localStorage.getItem('gitrank_subscribers') || '[]');
      if (subs.length === 0) {
        subs = ['sample-subscriber@developer.io', 'lead-maintainer@techstart.dev'];
      }
      const csv = 'Email,SubscriptionDate\n' + subs.map(s => `${s},${new Date().toISOString()}`).join('\n');
      const blob = new Blob([csv], { type: 'text/csv' });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = 'gitrank_subscribers.csv';
      a.click();
      URL.revokeObjectURL(url);
      showToast(`Exported ${subs.length} subscriber emails to CSV`);
    }

